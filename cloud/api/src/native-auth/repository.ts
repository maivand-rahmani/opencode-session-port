/**
 * Build the repository. Both explicit pending caps are validated before the
 * client is captured.
 */
export function createNativeAuthRepository(
  client: NativeAuthRepositoryClient,
  options: NativeAuthRepositoryOptions,
): NativeAuthRepository {
  const maxOutstandingPendingAuthorizationsGlobal =
    readMaxOutstandingPendingAuthorizationsGlobal(options);
  const maxOutstandingPendingAuthorizationsPerUser =
    readMaxOutstandingPendingAuthorizationsPerUser(options);

  return Object.freeze({
    createPendingAuthorization: (input: CreatePendingAuthorizationInput) =>
      createPendingAuthorization(
        client,
        maxOutstandingPendingAuthorizationsGlobal,
        input,
      ),
    findVerificationPending: (
      candidates: readonly HumanCodeCandidate[],
      at: Date,
    ) => findVerificationPending(client, candidates, at),
    decidePendingAuthorization: (input: DecidePendingAuthorizationInput) =>
      decidePendingAuthorization(
        client,
        maxOutstandingPendingAuthorizationsPerUser,
        input,
      ),
    exchangeDeviceCode: (input: ExchangeDeviceCodeInput) =>
      exchangeDeviceCode(client, input),
    rotateRefreshToken: (input: RotateRefreshTokenInput) =>
      rotateRefreshToken(client, input),
    listGrants: (userID: string) => listGrants(client, userID),
    revokeGrant: (userID: string, grantID: string, at: Date) =>
      revokeGrant(client, userID, grantID, at),
  });
}

async function createPendingAuthorization(
  client: NativeAuthRepositoryClient,
  maxOutstanding: number,
  rawInput: CreatePendingAuthorizationInput,
): Promise<PendingAuthorizationRow> {
  const input = readCreatePendingInput(rawInput);

  try {
    return await client.$transaction(
      async (transaction) => {
        const outstanding =
          await transaction.nativePendingAuthorization.count({
            where: {
              status: { in: ['pending', 'approved'] },
              expiresAt: { gt: input.createdAt },
            },
          });
        if (outstanding >= maxOutstanding) {
          throw new NativeAuthRepositoryError('capacity-reached');
        }

        return transaction.nativePendingAuthorization.create({
          data: {
            id: input.id,
            deviceCodeFingerprint: input.deviceCodeFingerprint,
            humanCodeDigest: new Uint8Array(input.humanCodeDigest),
            humanCodeKeyID: input.humanCodeKeyID,
            status: 'pending',
            audience: input.audience,
            resource: input.resource,
            scopes: [...input.scopes],
            createdAt: input.createdAt,
            expiresAt: input.expiresAt,
            pollIntervalSeconds: input.pollIntervalSeconds,
          },
          select: PENDING_SELECT,
        });
      },
      { isolationLevel: 'Serializable' },
    );
  } catch (error) {
    throw sanitizeRepositoryError(error);
  }
}

async function findVerificationPending(
  client: NativeAuthRepositoryClient,
  rawCandidates: readonly HumanCodeCandidate[],
  rawAt: Date,
): Promise<PendingAuthorizationRow | null> {
  const candidates = readCandidates(rawCandidates);
  const at = readDate(rawAt);

  if (candidates.length === 0) {
    return null;
  }

  try {
    for (const candidate of candidates) {
      const row = await client.nativePendingAuthorization.findUnique({
        where: {
          humanCodeKeyID_humanCodeDigest: {
            humanCodeKeyID: candidate.keyID,
            humanCodeDigest: new Uint8Array(candidate.digest),
          },
        },
        select: PENDING_SELECT,
      });
      if (row === null) continue;
      if (row.status !== 'pending') continue;
      if (row.expiresAt.getTime() <= at.getTime()) continue;
      if (!rowMatchesCandidate(row, candidate)) continue;
      return row;
    }
    return null;
  } catch (error) {
    throw sanitizeRepositoryError(error);
  }
}

async function decidePendingAuthorization(
  client: NativeAuthRepositoryClient,
  maxOutstandingPendingAuthorizationsPerUser: number,
  rawInput: DecidePendingAuthorizationInput,
): Promise<DecidePendingAuthorizationOutcome> {
  const input = readDecideInput(rawInput);

  try {
    return await client.$transaction(
      async (transaction) => {
        let sawExpired = false;
        let sawNonPending = false;

        for (const candidate of input.candidates) {
          const found =
            await transaction.nativePendingAuthorization.findUnique({
              where: {
                humanCodeKeyID_humanCodeDigest: {
                  humanCodeKeyID: candidate.keyID,
                  humanCodeDigest: new Uint8Array(candidate.digest),
                },
              },
              select: { id: true },
            });
          if (found === null) continue;

          const pending = await lockPendingById(transaction, found.id);
          if (pending === null) continue;
          if (!rowMatchesCandidate(pending, candidate)) continue;

          // A key-rotation overlap can leave the same human code associated
          // with an old non-pending row and a newer pending row. Prefer the
          // pending row; only report expiry/conflict if no pending match
          // exists across all eligible keys.
          if (pending.status !== 'pending') {
            sawNonPending = true;
            continue;
          }
          if (pending.expiresAt.getTime() <= input.at.getTime()) {
            sawExpired = true;
            continue;
          }

          if (input.decision === 'approve') {
            const approvedOutstanding =
              await transaction.nativePendingAuthorization.count({
                where: {
                  status: 'approved',
                  approvedUserID: input.userID as string,
                  expiresAt: { gt: input.at },
                },
              });
            if (
              approvedOutstanding >=
              maxOutstandingPendingAuthorizationsPerUser
            ) {
              throw new NativeAuthRepositoryError('capacity-reached');
            }

            const updated =
              await transaction.nativePendingAuthorization.update({
                where: { id: pending.id },
                data: {
                  status: 'approved',
                  approvedUserID: input.userID as string,
                },
                select: PENDING_SELECT,
              });
            return { kind: 'approved' as const, pending: updated };
          }

          const updated =
            await transaction.nativePendingAuthorization.update({
              where: { id: pending.id },
              data: { status: 'denied' },
              select: PENDING_SELECT,
            });
          return { kind: 'denied' as const, pending: updated };
        }

        if (sawExpired) {
          return { kind: 'expired' as const };
        }
        if (sawNonPending) {
          return { kind: 'state-conflict' as const };
        }
        return { kind: 'not-found' as const };
      },
      {
        isolationLevel:
          input.decision === 'approve' ? 'Serializable' : 'ReadCommitted',
      },
    );
  } catch (error) {
    throw sanitizeRepositoryError(error);
  }
}

async function exchangeDeviceCode(
  client: NativeAuthRepositoryClient,
  rawInput: ExchangeDeviceCodeInput,
): Promise<ExchangeDeviceCodeOutcome> {
  const input = readExchangeInput(rawInput);

  try {
    return await client.$transaction(
      async (transaction) => {
        const pending = await lockPendingByDeviceCodeFingerprint(
          transaction,
          input.deviceCodeFingerprint,
        );
        if (pending === null) {
          return { kind: 'invalid-credential' as const };
        }

        // Terminal states remain distinct even after their expiry timestamp;
        // expiry applies to a still-pending or approved authorization.
        if (pending.status === 'denied') {
          return { kind: 'authorization-denied' as const };
        }
        if (pending.status === 'consumed') {
          return { kind: 'authorization-consumed' as const };
        }
        if (pending.expiresAt.getTime() <= input.now.getTime()) {
          return { kind: 'authorization-expired' as const };
        }
        if (pending.status === 'pending') {
          return updatePendingPoll(transaction, pending, input.now, input.polling);
        }
        if (
          pending.status !== 'approved' ||
          pending.approvedUserID === null
        ) {
          return { kind: 'state-conflict' as const };
        }

        // Pending -> quota -> grant creation. No other transaction takes the
        // quota lock before a pending lock, so this order cannot cycle with
        // approval, refresh, or revocation.
        const quota = await lockQuotaRow(transaction, pending.approvedUserID);
        if (!quota) {
          return { kind: 'quota-not-provisioned' as const };
        }

        const activeGrantCount = await transaction.nativeDeviceGrant.count({
          where: {
            userID: pending.approvedUserID,
            status: 'active',
            expiresAt: { gt: input.now },
          },
        });
        if (activeGrantCount >= input.maxActiveGrantsPerUser) {
          return { kind: 'active-grant-limit' as const };
        }

        const grant = await transaction.nativeDeviceGrant.create({
          data: {
            id: input.grantID,
            userID: pending.approvedUserID,
            status: 'active',
            audience: pending.audience,
            resource: pending.resource,
            scopes: [...pending.scopes],
            createdAt: input.now,
            expiresAt: input.grantExpiresAt,
          },
          select: { id: true, scopes: true },
        });

        await transaction.device.create({
          data: {
            id: input.deviceID,
            userID: pending.approvedUserID,
            grantID: grant.id,
            createdAt: input.now,
          },
        });

        await transaction.nativeAccessToken.create({
          data: {
            id: input.access.id,
            fingerprint: input.access.fingerprint,
            grantID: grant.id,
            createdAt: input.now,
            expiresAt: input.access.expiresAt,
          },
        });

        await transaction.nativeRefreshToken.create({
          data: {
            id: input.refresh.id,
            fingerprint: input.refresh.fingerprint,
            grantID: grant.id,
            createdAt: input.now,
            expiresAt: input.refresh.expiresAt,
          },
        });

        await transaction.nativePendingAuthorization.update({
          where: { id: pending.id },
          data: { status: 'consumed', consumedAt: input.now },
        });

        return {
          kind: 'tokens' as const,
          grantID: grant.id,
          scope: grant.scopes.join(' '),
          expiresIn: positiveSecondsBetween(input.now, input.access.expiresAt),
        };
      },
      { isolationLevel: 'ReadCommitted' },
    );
  } catch (error) {
    throw sanitizeRepositoryError(error);
  }
}

async function rotateRefreshToken(
  client: NativeAuthRepositoryClient,
  rawInput: RotateRefreshTokenInput,
): Promise<RotateRefreshTokenOutcome> {
  const input = readRotateInput(rawInput);

  let preRead: { readonly grantID: string } | null;
  try {
    preRead = await client.nativeRefreshToken.findUnique({
      where: { fingerprint: input.refreshTokenFingerprint },
      select: { grantID: true },
    });
  } catch (error) {
    throw sanitizeRepositoryError(error);
  }
  if (preRead === null) {
    return { kind: 'invalid-credential' };
  }

  try {
    return await client.$transaction(
      async (transaction) => {
        const grant = await lockGrantById(transaction, preRead.grantID);
        if (grant === null) {
          return { kind: 'invalid-credential' as const };
        }

        const token = await lockRefreshTokenByFingerprint(
          transaction,
          input.refreshTokenFingerprint,
        );
        if (token === null || token.grantID !== grant.id) {
          return { kind: 'invalid-credential' as const };
        }

        // Replay is the only refresh failure that mutates state. The grant
        // revocation is committed here; the caller throws the public error
        // only after this transaction returns.
        if (token.spentAt !== null || token.successorID !== null) {
          if (grant.status === 'active') {
            await transaction.nativeDeviceGrant.update({
              where: { id: grant.id },
              data: { status: 'revoked', revokedAt: input.now },
            });
          }
          return { kind: 'replay' as const };
        }

        if (
          grant.status !== 'active' ||
          grant.expiresAt.getTime() <= input.now.getTime()
        ) {
          return { kind: 'invalid-credential' as const };
        }
        if (token.expiresAt.getTime() <= input.now.getTime()) {
          return { kind: 'invalid-credential' as const };
        }
        if (token.expiresAt.getTime() > grant.expiresAt.getTime()) {
          return { kind: 'invalid-credential' as const };
        }

        const user = await transaction.user.findUnique({
          where: { id: grant.userID },
          select: { id: true },
        });
        if (user === null) {
          return { kind: 'invalid-credential' as const };
        }

        const device = await transaction.device.findUnique({
          where: { grantID: grant.id },
          select: { id: true, userID: true },
        });
        if (device === null || device.userID !== grant.userID) {
          return { kind: 'invalid-credential' as const };
        }

        const accessExpiresAt = earlierDate(
          addSeconds(input.now, input.accessTokenTTLSeconds),
          grant.expiresAt,
        );
        const refreshExpiresAt = earlierDate(
          addSeconds(input.now, input.refreshTokenTTLSeconds),
          grant.expiresAt,
        );
        if (
          accessExpiresAt.getTime() <= input.now.getTime() ||
          refreshExpiresAt.getTime() <= input.now.getTime()
        ) {
          throw new NativeAuthRepositoryError('invalid-input');
        }

        // Insert the successor first so the old row's unique successor FK
        // always points at an existing row, then mark the old row spent.
        await transaction.nativeRefreshToken.create({
          data: {
            id: input.refresh.id,
            fingerprint: input.refresh.fingerprint,
            grantID: grant.id,
            createdAt: input.now,
            expiresAt: refreshExpiresAt,
          },
        });

        await transaction.nativeAccessToken.create({
          data: {
            id: input.access.id,
            fingerprint: input.access.fingerprint,
            grantID: grant.id,
            createdAt: input.now,
            expiresAt: accessExpiresAt,
          },
        });

        await transaction.nativeRefreshToken.update({
          where: { id: token.id },
          data: { spentAt: input.now, successorID: input.refresh.id },
        });

        return {
          kind: 'tokens' as const,
          grantID: grant.id,
          scope: grant.scopes.join(' '),
          expiresIn: positiveSecondsBetween(input.now, accessExpiresAt),
        };
      },
      { isolationLevel: 'ReadCommitted' },
    );
  } catch (error) {
    throw sanitizeRepositoryError(error);
  }
}

async function listGrants(
  client: NativeAuthRepositoryClient,
  rawUserID: string,
): Promise<readonly GrantListRow[]> {
  const userID = readUserID(rawUserID);

  try {
    const rows = await client.nativeDeviceGrant.findMany({
      where: { userID },
      orderBy: { createdAt: 'desc' },
      select: GRANT_LIST_SELECT,
    });

    return Object.freeze(
      rows.map((row) => {
        if (row.device === null) {
          throw new NativeAuthRepositoryError('unavailable');
        }
        return Object.freeze({
          id: row.id,
          status: row.status,
          createdAt: row.createdAt,
          expiresAt: row.expiresAt,
          revokedAt: row.revokedAt,
          deviceID: row.device.id,
          lastSeenAt: row.device.lastSeenAt,
        });
      }),
    );
  } catch (error) {
    throw sanitizeRepositoryError(error);
  }
}

async function revokeGrant(
  client: NativeAuthRepositoryClient,
  rawUserID: string,
  rawGrantID: string,
  rawAt: Date,
): Promise<RevokeGrantOutcome> {
  const userID = readUserID(rawUserID);
  const grantID = readUUID(rawGrantID);
  const at = readDate(rawAt);

  try {
    return await client.$transaction(
      async (transaction) => {
        const grant = await lockGrantById(transaction, grantID);
        if (grant === null || grant.userID !== userID) {
          return { kind: 'not-found' as const };
        }

        const current =
          grant.status === 'active'
            ? await transaction.nativeDeviceGrant.update({
                where: { id: grant.id },
                data: { status: 'revoked', revokedAt: at },
              })
            : grant;

        const device = await transaction.device.findUnique({
          where: { grantID: current.id },
          select: { id: true, lastSeenAt: true },
        });
        if (device === null) {
          throw new NativeAuthRepositoryError('unavailable');
        }

        return {
          kind: 'revoked' as const,
          grant: Object.freeze({
            id: current.id,
            status: current.status,
            createdAt: current.createdAt,
            expiresAt: current.expiresAt,
            revokedAt: current.revokedAt,
            deviceID: device.id,
            lastSeenAt: device.lastSeenAt,
          }),
        };
      },
      { isolationLevel: 'ReadCommitted' },
    );
  } catch (error) {
    throw sanitizeRepositoryError(error);
  }
}

