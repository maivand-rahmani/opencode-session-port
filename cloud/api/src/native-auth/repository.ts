async function updatePendingPoll(
  transaction: Transaction,
  pending: PendingAuthorizationRow,
  now: Date,
  polling: NativePollingPolicy,
): Promise<
  | {
      readonly kind: 'authorization-pending';
      readonly retryAfterSeconds: number;
    }
  | { readonly kind: 'slow-down'; readonly retryAfterSeconds: number }
> {
  const base = Math.min(
    Math.max(pending.pollIntervalSeconds, 1),
    polling.maxIntervalSeconds,
  );
  const early =
    pending.nextPollAt !== null &&
    Number.isFinite(pending.nextPollAt.getTime()) &&
    now.getTime() < pending.nextPollAt.getTime();

  const grown =
    base > polling.maxIntervalSeconds - polling.backoffIncrementSeconds
      ? polling.maxIntervalSeconds
      : base + polling.backoffIncrementSeconds;
  const interval = early ? grown : base;
  const nextPollAt = new Date(now.getTime() + interval * 1_000);

  await transaction.nativePendingAuthorization.update({
    where: { id: pending.id },
    data: {
      lastPolledAt: now,
      nextPollAt,
      pollIntervalSeconds: interval,
    },
  });

  return early
    ? { kind: 'slow-down' as const, retryAfterSeconds: interval }
    : { kind: 'authorization-pending' as const, retryAfterSeconds: interval };
}

function rowMatchesCandidate(
  row: PendingAuthorizationRow,
  candidate: HumanCodeCandidate,
): boolean {
  return (
    row.humanCodeKeyID === candidate.keyID &&
    humanCodeDigestsEqual(row.humanCodeDigest, candidate.digest)
  );
}

