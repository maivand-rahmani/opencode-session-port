function readTokenInsert(rawInput: NativeTokenInsert): NativeTokenInsert {
  if (
    typeof rawInput !== 'object' ||
    rawInput === null ||
    Array.isArray(rawInput)
  ) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  return {
    id: readUUID(rawInput.id),
    fingerprint: readFingerprint(rawInput.fingerprint),
    expiresAt: readDate(rawInput.expiresAt),
  };
}

function readCandidates(
  rawCandidates: readonly HumanCodeCandidate[],
): readonly HumanCodeCandidate[] {
  if (!Array.isArray(rawCandidates)) {
    throw new NativeAuthRepositoryError('invalid-input');
  }

  const seen = new Set<string>();
  const candidates: HumanCodeCandidate[] = [];
  for (const rawCandidate of rawCandidates) {
    if (
      typeof rawCandidate !== 'object' ||
      rawCandidate === null ||
      Array.isArray(rawCandidate)
    ) {
      throw new NativeAuthRepositoryError('invalid-input');
    }
    const keyID = readHumanCodeKeyID(rawCandidate.keyID);
    const digest = readDigest(rawCandidate.digest);
    const mapKey = `${keyID}\0${Buffer.from(digest).toString('hex')}`;
    if (seen.has(mapKey)) {
      throw new NativeAuthRepositoryError('invalid-input');
    }
    seen.add(mapKey);
    candidates.push(Object.freeze({ keyID, digest }));
  }
  return Object.freeze(candidates);
}

function readDigest(value: unknown): Uint8Array {
  if (!(value instanceof Uint8Array) || value.byteLength !== HUMAN_CODE_DIGEST_BYTES) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  return new Uint8Array(value);
}

function readHumanCodeKeyID(value: unknown): string {
  if (
    typeof value !== 'string' ||
    value.length === 0 ||
    value.length > MAX_HUMAN_CODE_KEY_ID_LENGTH ||
    CONTROL_CHARACTERS.test(value)
  ) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  return value;
}

function readFingerprint(value: unknown): string {
  if (typeof value !== 'string' || !FINGERPRINT_PATTERN.test(value)) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  return value;
}

function readUUID(value: unknown): string {
  if (typeof value !== 'string' || !UUID_PATTERN.test(value)) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  return value.toLowerCase();
}

function readUserID(value: unknown): string {
  if (
    typeof value !== 'string' ||
    value.length === 0 ||
    value.length > MAX_USER_ID_LENGTH ||
    value.trim().length === 0 ||
    CONTROL_CHARACTERS.test(value)
  ) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  return value;
}

function readIdentifier(value: unknown): string {
  if (
    typeof value !== 'string' ||
    value.length === 0 ||
    value.length > MAX_IDENTIFIER_LENGTH ||
    value.trim() !== value ||
    CONTROL_CHARACTERS.test(value)
  ) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  return value;
}

function readScopes(value: unknown): readonly string[] {
  if (!Array.isArray(value) || value.length === 0) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  const seen = new Set<string>();
  const scopes: string[] = [];
  for (const scope of value) {
    if (
      typeof scope !== 'string' ||
      scope.length === 0 ||
      scope.length > MAX_SCOPE_LENGTH ||
      CONTROL_CHARACTERS.test(scope) ||
      seen.has(scope)
    ) {
      throw new NativeAuthRepositoryError('invalid-input');
    }
    seen.add(scope);
    scopes.push(scope);
  }
  return Object.freeze(scopes);
}

function readPollingPolicy(value: unknown): NativePollingPolicy {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  const polling = value as {
    readonly intervalSeconds?: unknown;
    readonly backoffIncrementSeconds?: unknown;
    readonly maxIntervalSeconds?: unknown;
  };
  const intervalSeconds = readPositiveInteger(polling.intervalSeconds);
  const backoffIncrementSeconds = readPositiveInteger(
    polling.backoffIncrementSeconds,
  );
  const maxIntervalSeconds = readPositiveInteger(polling.maxIntervalSeconds);
  if (
    maxIntervalSeconds < intervalSeconds ||
    backoffIncrementSeconds > maxIntervalSeconds
  ) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  return Object.freeze({
    intervalSeconds,
    backoffIncrementSeconds,
    maxIntervalSeconds,
  });
}

function readPositiveInteger(value: unknown): number {
  if (
    typeof value !== 'number' ||
    !Number.isSafeInteger(value) ||
    value <= 0
  ) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  return value;
}

function readDate(value: unknown): Date {
  if (!(value instanceof Date) || !Number.isFinite(value.getTime())) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  return new Date(value.getTime());
}

function addSeconds(at: Date, seconds: number): Date {
  const value = at.getTime() + seconds * 1_000;
  if (!Number.isFinite(value)) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  return new Date(value);
}

function earlierDate(left: Date, right: Date): Date {
  return left.getTime() <= right.getTime()
    ? new Date(left.getTime())
    : new Date(right.getTime());
}

function positiveSecondsBetween(from: Date, to: Date): number {
  const milliseconds = to.getTime() - from.getTime();
  if (!Number.isSafeInteger(milliseconds) || milliseconds <= 0) {
    throw new NativeAuthRepositoryError('invalid-input');
  }
  return Math.max(1, Math.floor(milliseconds / 1_000));
}

function isPrismaCode(error: unknown, code: string): boolean {
  return (
    typeof error === 'object' &&
    error !== null &&
    (error as { readonly code?: unknown }).code === code
  );
}

function sanitizeRepositoryError(error: unknown): NativeAuthRepositoryError {
  if (error instanceof NativeAuthRepositoryError) {
    return error;
  }
  if (isPrismaCode(error, 'P2002')) {
    return new NativeAuthRepositoryError('unique-collision');
  }
  if (isPrismaCode(error, 'P2034')) {
    return new NativeAuthRepositoryError('serialization-failure');
  }
  return new NativeAuthRepositoryError('unavailable');
}


