/**
 * Native-auth persistence and transaction primitives.
 *
 * This module owns the database-facing lifecycle steps only. It never handles
 * HTTP, browser sessions, raw human codes, rate limits, or response logging.
 * Callers must supply already-generated identifiers, credential fingerprints,
 * and a server-owned policy.
 *
 * Fixed transaction order (documented invariants):
 *   create:   SERIALIZABLE count of unexpired pending/approved rows, then insert.
 *             No advisory lock and no automatic retry.
 *   approve:  pending row FOR UPDATE, then SERIALIZABLE count of unexpired
 *             approved rows for the authoritative user, then update.
 *   deny:     pending row FOR UPDATE only (ReadCommitted).
 *   exchange: pending row FOR UPDATE -> UserQuota row FOR UPDATE -> grant ->
 *             device -> access token -> refresh token -> pending consumed.
 *   refresh:  grant FOR UPDATE -> refresh token FOR UPDATE -> rotation.
 *   revoke:   grant FOR UPDATE -> ownership check -> revoked.
 *
 * Every raw SQL statement is a constant tagged template; identifiers are
 * generated by callers and every user/row value is a bound parameter.
 *
 * Pending-capacity note: the schema has no per-user or global capacity-slot
 * row. Public creation enforces the explicit global cap from
 * `repositoryPolicy`. Approval enforces the explicit per-user cap from
 * `NativeAuthConfig` after the authoritative browser user is bound; the
 * predicate count and existing pending-row lock run in the same SERIALIZABLE
 * transaction so two distinct concurrent approvals cannot both commit past the
 * cap. A Prisma P2034 is reported as a retryable serialization failure and is
 * never retried here. This is a source-level concurrency strategy; no real
 * PostgreSQL contention proof is claimed by these tests.
 */

